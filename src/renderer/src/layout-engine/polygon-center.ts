/**
 * The center of the box around a polygon's points. A polygon's x and y are where this point
 * is, the same convention as a rectangle or ellipse: the canvas draws it there and turns it
 * about it, and the 3D model must cut it there too.
 */
export function polygonBboxCenter(points: { x: number; y: number }[]): { x: number; y: number } {
  if (points.length === 0) return { x: 0, y: 0 }
  let minX = Infinity
  let maxX = -Infinity
  let minY = Infinity
  let maxY = -Infinity
  for (const p of points) {
    if (p.x < minX) minX = p.x
    if (p.x > maxX) maxX = p.x
    if (p.y < minY) minY = p.y
    if (p.y > maxY) maxY = p.y
  }
  return { x: (minX + maxX) / 2, y: (minY + maxY) / 2 }
}
